/**
 * Get category display name based on current language
 */
export const getCategoryLabel = (cat, lang = 'en') => {
  if (CATEGORY_TRANSLATIONS[cat]) {
    return CATEGORY_TRANSLATIONS[cat][lang] || cat;
  }
  return cat;
};
